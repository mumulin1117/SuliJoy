import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createCipheriv, createDecipheriv, randomBytes, createHash } from 'node:crypto'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const schemePath = path.join(__dirname, '../config/opi-scheme.v1.json')

function collectFieldPairs(fields) {
  const pairs = []
  const seen = new Set()
  for (const field of fields ?? []) {
    const original = field.originalName
    const alias = field.alias
    if (!original || !alias || original === alias) continue
    const token = `${original}->${alias}`
    if (seen.has(token)) continue
    seen.add(token)
    pairs.push({ original, alias })
  }
  return pairs
}

function buildRegistry(doc) {
  const headerAliases = {}
  for (const header of doc.headers ?? []) {
    if (header.alias) headerAliases[header.originalName] = header.alias
  }

  const pathAliases = {}
  const requestFieldsByPath = {}
  const responseFieldsByPath = {}

  for (const item of doc.interfaces ?? []) {
    if (!item.enabled) continue
    const originalPath = item.originalPath
    const aliasPath = item.aliasPath
    if (!originalPath || !aliasPath) continue
    pathAliases[originalPath] = aliasPath
    const requestPairs = collectFieldPairs(item.requestFields)
    const responsePairs = collectFieldPairs(item.responseFields)
    if (requestPairs.length) requestFieldsByPath[originalPath] = requestPairs
    if (responsePairs.length) responseFieldsByPath[originalPath] = responsePairs
  }

  const envelopePairs = collectFieldPairs(
    (doc.interfaces ?? []).flatMap((item) => item.responseFields ?? []).filter((field) =>
      ['code', 'message', 'requestId', 'result'].includes(field.originalName),
    ),
  )
  const envelope = Object.fromEntries(envelopePairs.map((pair) => [pair.original, pair.alias]))

  return {
    schemeCode: doc.scheme?.schemeCode ?? '',
    basePath: doc.scheme?.basePath ?? '',
    appId: doc.project?.appId ?? '',
    headerAliases,
    pathAliases,
    requestFieldsByPath,
    responseFieldsByPath,
    envelope,
  }
}

function emitTypeScript(registry) {
  const serialize = (value) => JSON.stringify(value, null, 2)
  return `/* eslint-disable */
// Generated by scripts/generate-opi-registry.mjs — do not edit manually.
export const OPI_SCHEME_CODE = ${JSON.stringify(registry.schemeCode)}
export const OPI_BASE_PATH = ${JSON.stringify(registry.basePath)}
export const OPI_PROJECT_APP_ID = ${JSON.stringify(registry.appId)}

export const OPI_HEADER_ALIASES: Readonly<Record<string, string>> = ${serialize(registry.headerAliases)}

export const OPI_PATH_ALIASES: Readonly<Record<string, string>> = ${serialize(registry.pathAliases)}

export type OpFieldPair = { readonly original: string; readonly alias: string }

export const OPI_REQUEST_FIELDS_BY_PATH: Readonly<
  Record<string, readonly OpFieldPair[]>
> = ${serialize(registry.requestFieldsByPath)}

export const OPI_RESPONSE_FIELDS_BY_PATH: Readonly<
  Record<string, readonly OpFieldPair[]>
> = ${serialize(registry.responseFieldsByPath)}

export const OPI_ENVELOPE_FIELD_ALIASES: Readonly<Record<string, string>> = ${serialize(registry.envelope)}
`
}

async function main() {
  const raw = await readFile(schemePath, 'utf8')
  const doc = JSON.parse(raw)
  const registry = buildRegistry(doc)
  const tsOut = path.join(__dirname, '../src/core/api/opi-registry.generated.ts')
  const swiftOut = path.join(__dirname, '../../JOiySuizoy/JOiySuizoy/SuliJoyOpiRegistry.swift')
  const swiftJsonOut = path.join(__dirname, '../../JOiySuizoy/JOiySuizoy/SuliJoyOpiRegistry.json')
  // Keep the maintained Swift loader and legacy identifiers intact. Never emit
  // the old plaintext loader or plaintext iOS resource again.
  const swift = await readFile(swiftOut, 'utf8')
  const keyMatch = swift.match(/private static let [A-Za-z_][A-Za-z_0-9]* = SymmetricKey\(data: Data\(\[([\d,\s]+)\]\)\)/)
  if (!keyMatch || !swift.includes('AES.GCM.open')) throw new Error('Encrypted iOS loader not configured')
  const key = Buffer.from(keyMatch[1].split(',').map((part) => Number(part.trim())))
  if (key.length !== 32) throw new Error('Registry requires a 256-bit key')
  const plaintext = Buffer.from(JSON.stringify(registry), 'utf8')
  if (process.argv.includes('--verify')) {
    const envelope = JSON.parse(await readFile(swiftJsonOut, 'utf8'))
    if (envelope.version !== 1) throw new Error('Unsupported registry format')
    const combined = Buffer.from(envelope.payload, 'base64')
    const decipher = createDecipheriv('aes-256-gcm', key, combined.subarray(0, 12))
    decipher.setAuthTag(combined.subarray(-16))
    const decoded = Buffer.concat([decipher.update(combined.subarray(12, -16)), decipher.final()])
    if (!decoded.equals(plaintext)) throw new Error('Registry differs from scheme configuration')
    console.log(`Verified encrypted registry: ${Object.keys(registry.pathAliases).length} paths, sha256=${createHash('sha256').update(decoded).digest('hex')}`)
    return
  }
  const nonce = randomBytes(12)
  const cipher = createCipheriv('aes-256-gcm', key, nonce)
  const ciphertext = Buffer.concat([cipher.update(plaintext), cipher.final()])
  // CryptoKit combined format: nonce (12) + ciphertext + authentication tag (16).
  const combined = Buffer.concat([nonce, ciphertext, cipher.getAuthTag()])
  await writeFile(tsOut, emitTypeScript(registry), 'utf8')
  await writeFile(swiftJsonOut, JSON.stringify({ version: 1, payload: combined.toString('base64') }), 'utf8')
  console.log(
    `Generated ${Object.keys(registry.pathAliases).length} path aliases -> ${path.relative(process.cwd(), tsOut)}`,
  )
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
